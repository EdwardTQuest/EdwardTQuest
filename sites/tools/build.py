def hub():
    """sites/index.html: the four houses on one screen, with their live title counts."""
    houses = []
    for h in HOUSES:
        path = os.path.join(ROOT, h['key'], 'catalog.js')
        if not os.path.exists(path):
            continue
        cat = json.loads(open(path).read().split('window.CATALOG = ', 1)[1].rstrip().rstrip(';'))
        houses.append(dict(h, count=len(cat['books'])))
    html = open(os.path.join(ROOT, 'hub.template.html')).read()
    html = html.replace('/*HOUSES*/[]', json.dumps(houses, ensure_ascii=False))
    with open(os.path.join(ROOT, 'index.html'), 'w') as f:
        f.write('<!-- Generated by tools/build.py from hub.template.html -->\n' + html)


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    for s in (args or SITES):
        if os.path.exists(os.path.join(ROOT, 'data', f'{s}.json')):
            build(s, '--all' in sys.argv)
        else:
            print(f'{s:<18} no data yet (data/{s}.json)')
    hub()
