#!/usr/bin/env python3
"""Build the shops from their data.

    python3 tools/build.py            # every site
    python3 tools/build.py scepter-uk # one site
    python3 tools/build.py --all      # also list titles the research marked doubtful

For each site: data/<site>.json + data/prices/<site>.csv  →  <site>/catalog.js
and a single self-contained page dist/<site>.html (fonts, styles, scripts and data inlined)
that opens from a laptop or phone with no network.

Prices: the owner's rule is one price per title, the Amazon price, for the book, the eBook and the
audiobook alike. Fill the `book` column of data/prices/<site>.csv with the Amazon price (and `source`
with the Amazon URL); leave `ebook` and `audiobook` empty to use the same price, or fill them to
override. `seen_elsewhere` records prices the research saw at other sellers, for reference only.
Unfilled titles show as "price to follow" and can still go in the basket."""
import base64, csv, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITES = ['scepter-uk', 'sinag-tala', 'scepter-kenya', 'scepter-australia']
SHOW = {'confirmed', 'likely', 'range'}
CURRENCY = {'scepter-uk': 'GBP', 'sinag-tala': 'PHP', 'scepter-kenya': 'KES', 'scepter-australia': 'AUD'}
COLS = ['id', 'title', 'author', 'isbn', 'book', 'ebook', 'audiobook', 'source', 'checked', 'seen_elsewhere']


def num(s):
    s = (s or '').strip().replace(',', '')
    s = re.sub(r'^[^\d.]+', '', s)
    try:
        return round(float(s), 2) if s else None
    except ValueError:
        return None


def prices(site, books):
    path = os.path.join(ROOT, 'data', 'prices', f'{site}.csv')
    rows = {}
    if os.path.exists(path):
        with open(path, newline='') as f:
            for row in csv.DictReader(f):
                rows[row['id']] = row
    cur = CURRENCY[site]
    for b in books:
        if b['id'] in rows:
            continue
        # Prices the research saw at other sellers are kept for reference only: the site shows Amazon's.
        seen = '; '.join(f"{p['amount']:g} {p['currency']} at {p.get('url') or p.get('source', '')}" for p in b.get('prices_seen', []))
        rows[b['id']] = {
            'id': b['id'], 'title': b['title'], 'author': b['author'], 'isbn': b.get('isbn', ''),
            'book': '', 'ebook': '', 'audiobook': '', 'source': '', 'checked': '', 'seen_elsewhere': seen,
        }
    order = [b['id'] for b in books] + [k for k in rows if k not in {b['id'] for b in books}]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=COLS)
        w.writeheader()
        for k in order:
            w.writerow({c: rows[k].get(c, '') for c in COLS})
    out = {}
    for k, row in rows.items():
        p = num(row.get('book'))
        out[k] = {'print': p, 'ebook': num(row.get('ebook')) or p, 'audio': num(row.get('audiobook')) or p}
    return out


def build(site, show_all=False):
    data = json.load(open(os.path.join(ROOT, 'data', f'{site}.json')))
    books = [b for b in data['books'] if show_all or b.get('status') in SHOW]
    price = prices(site, data['books'])
    shelves = [s for s in data['shelves'] if any(b['shelf'] == s['slug'] for b in books)]
    cat = {
        'generated': data.get('compiled', ''),
        'shelves': shelves,
        'books': [{
            'id': b['id'], 'title': b['title'], 'subtitle': b.get('subtitle', ''), 'author': b.get('author', ''),
            'shelf': b['shelf'], 'kind': b.get('kind', 'book'), 'description': b.get('description', ''),
            'isbn': b.get('isbn', ''), 'pages': b.get('pages') or 0, 'featured': bool(b.get('featured')),
            'price': price.get(b['id'], {'print': None, 'ebook': None, 'audio': None}),
        } for b in books],
    }
    js = '/* Generated by tools/build.py from data/%s.json and data/prices/%s.csv — edit those, not this. */\nwindow.CATALOG = %s;\n' % (
        site, site, json.dumps(cat, ensure_ascii=False, separators=(',', ':')))
    with open(os.path.join(ROOT, site, 'catalog.js'), 'w') as f:
        f.write(js)
    priced = sum(1 for b in cat['books'] if b['price']['print'] is not None)
    held = len(data['books']) - len(books)
    print(f"{site:<18} {len(books):>3} titles on {len(shelves)} shelves · {priced} priced · {held} held back (doubtful) · {len(data.get('dropped', []))} dropped by research")
    single(site)


def single(site):
    """Inline every stylesheet, script, font and icon into one HTML file."""
    base = os.path.join(ROOT, site)
    html = open(os.path.join(base, 'index.html')).read()

    def read(rel):
        return open(os.path.normpath(os.path.join(base, rel))).read()

    def css(rel):
        text = read(rel)
        folder = os.path.dirname(os.path.normpath(os.path.join(base, rel)))

        def font(m):
            p = os.path.join(folder, m.group(1))
            return 'url(data:font/woff2;base64,%s)' % base64.b64encode(open(p, 'rb').read()).decode()
        return re.sub(r'url\((fonts/[^)]+\.woff2)\)', font, text)

    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', lambda m: '<style>\n%s</style>' % css(m.group(1)), html)
    html = re.sub(r'<script src="([^"]+)"></script>', lambda m: '<script>\n%s</script>' % read(m.group(1)).replace('</script', '<\\/script'), html)
    html = re.sub(r'<link rel="icon" href="([^"]+\.svg)" type="image/svg\+xml">',
                  lambda m: '<link rel="icon" type="image/svg+xml" href="data:image/svg+xml;base64,%s">' % base64.b64encode(read(m.group(1)).encode()).decode(), html)
    os.makedirs(os.path.join(ROOT, 'dist'), exist_ok=True)
    with open(os.path.join(ROOT, 'dist', f'{site}.html'), 'w') as f:
        f.write(html)


